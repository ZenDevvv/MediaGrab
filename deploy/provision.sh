#!/usr/bin/env bash
# Provision a MediaGrab hosted instance on a fresh Linux VM.
#
# Idempotent by design: Freestyle VMs may be ephemeral with no persistent
# volume, so this must succeed on an empty machine and on a re-run over an
# existing install.
#
# Usage (on the VM):
#   bash deploy/provision.sh
set -euo pipefail

APP_DIR="${APP_DIR:-/opt/mediagrab}"
ENV_FILE="${ENV_FILE:-/etc/mediagrab.env}"
REPO_REF="${REPO_REF:-main}"
SERVICE_NAME=mediagrab

log() { printf '[provision] %s\n' "$*"; }

# --- system packages ------------------------------------------------------
log "Installing system packages"
if command -v apt-get >/dev/null 2>&1; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y --no-install-recommends \
    python3 python3-venv python3-pip ffmpeg curl ca-certificates rsync unzip
else
  log "WARN: non-Debian system; skipping package install"
fi

# --- source ---------------------------------------------------------------
log "Fetching source ($REPO_REF)"
mkdir -p "$APP_DIR"
if [ -d "$APP_DIR/.git" ]; then
  git -C "$APP_DIR" fetch --depth 1 origin "$REPO_REF"
  git -C "$APP_DIR" reset --hard "origin/$REPO_REF"
else
  git clone --depth 1 --branch "$REPO_REF" \
    https://github.com/ZenDevvv/MediaGrab.git "$APP_DIR"
fi

# --- python environment ---------------------------------------------------
log "Building virtualenv"
python3 -m venv "$APP_DIR/venv"
"$APP_DIR/venv/bin/pip" install --quiet --upgrade pip
"$APP_DIR/venv/bin/pip" install --quiet -r "$APP_DIR/requirements.txt"
# uvicorn[standard] supplies the C extensions; confirm the importable form.
"$APP_DIR/venv/bin/python" -c "import uvicorn" || {
  log "ERROR: uvicorn missing"; exit 1; }

# --- runtime directories --------------------------------------------------
mkdir -p "$APP_DIR/downloads"

# --- Deno (yt-dlp JavaScript runtime) --------------------------------------
# yt-dlp cannot solve YouTube's player challenge without a JS runtime, and the
# app's default YTDLP_JS_RUNTIMES is "deno". A VM provisioned without this
# starts, serves, and then fails to extract from YouTube -- the exact failure
# the cookies and proxy below exist to prevent, reintroduced from the other end.
DENO_BIN=/usr/local/bin/deno
if ! command -v deno >/dev/null 2>&1; then
  log "Installing Deno"
  DENO_DIR=/usr/local/share/deno
  "$APP_DIR/venv/bin/python" "$APP_DIR/packaging/install_deno.py" --out "$DENO_DIR"
  ln -sf "$DENO_DIR/deno" "$DENO_BIN"
fi
if deno --version >/dev/null 2>&1; then
  log "Deno present: $(deno --version | head -1)"
else
  # Not fatal: every other platform still works, and /api/capabilities now
  # reports the missing runtime rather than hiding it.
  log "WARN: Deno did not install; YouTube extraction will be degraded"
fi

# --- configuration --------------------------------------------------------
# SESSION_SECRET must persist: without it every restart regenerates the key and
# resets every user's concurrency-gate history.
if [ ! -f "$ENV_FILE" ]; then
  log "Creating $ENV_FILE with a generated SESSION_SECRET"
  SECRET="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  cat > "$ENV_FILE" <<EOF
# MediaGrab hosted configuration.
# Generated by deploy/provision.sh -- do not commit.
SESSION_SECRET=$SECRET
# The app is reached through an ingress edge (a Freestyle style.dev TLS rule or
# a Cloudflare tunnel), never directly. Without this the client IP resolves to
# the socket peer -- the edge itself for every visitor -- which collapses the
# per-IP concurrency limit into a global one.
BEHIND_PROXY=true
DOWNLOADS_AVAILABLE=false
GITHUB_RELEASES_URL=https://github.com/ZenDevvv/MediaGrab/releases/latest
EOF
  chmod 600 "$ENV_FILE"
else
  log "Keeping existing $ENV_FILE (SESSION_SECRET preserved)"
fi

# --- YouTube cookies (optional) -------------------------------------------
# A datacenter IP triggers YouTube's bot check. Cookies exported from a real
# browser session are the standard workaround; see README for how to produce
# one. The file is a live credential -- 0600, root-owned, never committed.
COOKIE_FILE=/etc/mediagrab/ytdlp-cookies.txt
if [ -s "$COOKIE_FILE" ]; then
  log "Found YouTube cookie file; wiring MEDIA_GRAB_YTDLP_COOKIES"
  sudo chmod 600 "$COOKIE_FILE"
  if sudo grep -q "^MEDIA_GRAB_YTDLP_COOKIES=" "$ENV_FILE"; then
    sudo sed -i "s|^MEDIA_GRAB_YTDLP_COOKIES=.*|MEDIA_GRAB_YTDLP_COOKIES=$COOKIE_FILE|" "$ENV_FILE"
  else
    echo "MEDIA_GRAB_YTDLP_COOKIES=$COOKIE_FILE" | sudo tee -a "$ENV_FILE" >/dev/null
  fi
elif sudo grep -q "^MEDIA_GRAB_YTDLP_COOKIES=" "$ENV_FILE"; then
  log "No cookie file present; disabling MEDIA_GRAB_YTDLP_COOKIES"
  sudo sed -i "/^MEDIA_GRAB_YTDLP_COOKIES=/d" "$ENV_FILE"
fi

# Egress proxy (the root fix for the bot check) is passed through if set.
if [ -n "${MEDIA_GRAB_YTDLP_PROXY:-}" ]; then
  log "Configuring egress proxy"
  sudo sed -i "/^MEDIA_GRAB_YTDLP_PROXY=/d" "$ENV_FILE"
  echo "MEDIA_GRAB_YTDLP_PROXY=$MEDIA_GRAB_YTDLP_PROXY" | sudo tee -a "$ENV_FILE" >/dev/null
fi

# --- service --------------------------------------------------------------
log "Installing systemd unit"
install -m 644 "$APP_DIR/deploy/mediagrab.service" "/etc/systemd/system/$SERVICE_NAME.service"

# Optional: public exposure via a Cloudflare quick tunnel. Set ENABLE_TUNNEL=1.
# The quick tunnel yields a RANDOM *.trycloudflare.com hostname on every start,
# so it suits staging only -- use a named tunnel and your own domain for
# anything stable.
TUNNEL_NAME=mg-tunnel
TUNNEL_BIN=/usr/local/bin/cloudflared
if [ "${ENABLE_TUNNEL:-0}" = "1" ]; then
  if [ ! -x "$TUNNEL_BIN" ]; then
    log "Installing cloudflared"
    curl -sL -o /tmp/cloudflared \
      https://github.com/cloudflare/cloudflared/releases/latest/download/cloudflared-linux-amd64
    chmod +x /tmp/cloudflared
    install -m 755 /tmp/cloudflared "$TUNNEL_BIN"
    rm -f /tmp/cloudflared
  fi
  log "Installing $TUNNEL_NAME unit"
  install -m 644 "$APP_DIR/deploy/$TUNNEL_NAME.service" "/etc/systemd/system/$TUNNEL_NAME.service"
  systemctl daemon-reload
  systemctl enable "$TUNNEL_NAME" >/dev/null 2>&1 || true
  systemctl restart "$TUNNEL_NAME"
fi
systemctl daemon-reload
systemctl enable "$SERVICE_NAME" >/dev/null 2>&1 || true
systemctl restart "$SERVICE_NAME"

# --- readiness ------------------------------------------------------------
log "Waiting for readiness"
READY=0
for i in $(seq 1 40); do
  if CAPS="$(curl -fsS "http://127.0.0.1:8000/api/capabilities" 2>/dev/null)"; then
    READY=1
    break
  fi
  sleep 1
done

if [ "$READY" -ne 1 ]; then
  log "ERROR: service did not become ready"
  journalctl -u "$SERVICE_NAME" -n 50 --no-pager || true
  exit 1
fi

printf '%s\n' "$CAPS" | head -c 400; echo

# The service being up says nothing about whether YouTube will work, so check
# the runtime the way an operator would rather than discovering it from a
# support ticket.
if printf '%s' "$CAPS" | grep -q '"available":\[\]'; then
  log "WARN: no JavaScript runtime available; YouTube extraction is degraded"
  log "      fix: bash deploy/provision.sh, or install Deno on PATH"
fi